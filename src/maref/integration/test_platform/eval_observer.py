"""
MASEvalObserver — Injects MAS-TS-001 evaluation results into MAREF governance.

This module bridges the Agent Test Platform's evaluation reports with
MAREF's governance state machine, enabling:
  - Fast-Screen failures → automatic quarantine
  - Full-Run Layer 5 scores → dynamic phase governance
  - Real-time evaluation-driven state transitions
"""

from __future__ import annotations

import time
from collections.abc import Callable
from dataclasses import dataclass, field
from enum import Enum
from typing import Any

from maref.governance.state_machine import GovernanceStateMachine
from maref.governance.types import GovernanceState
from maref.integration.test_platform.schema import (
    EvalStatus,
    EvaluationReport,
)


class Phase(str, Enum):
    """Four-phase autonomy governance phases."""

    OLD_YANG = "old_yang"       # Maximum permissions
    LESSER_YANG = "lesser_yang" # Partial permissions
    LESSER_YIN = "lesser_yin"   # Restricted permissions
    OLD_YIN = "old_yin"         # Minimum permissions


@dataclass
class ObserverAlert:
    """Alert generated by the evaluation observer."""

    alert_id: str
    agent_id: str
    alert_type: str
    message: str
    severity: str
    timestamp: float = field(default_factory=time.time)
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "alert_id": self.alert_id,
            "agent_id": self.agent_id,
            "alert_type": self.alert_type,
            "message": self.message,
            "severity": self.severity,
            "timestamp": self.timestamp,
            "metadata": self.metadata,
        }


class MASEvalObserver:
    """
    Injects MAS-TS-001 evaluation results into MAREF governance state machine.

    Usage:
        observer = MASEvalObserver(governance_fsm)
        observer.on_fast_screen_complete(fast_screen_report)
        observer.on_full_run_complete(full_run_report)
    """

    def __init__(
        self,
        governance_fsm: GovernanceStateMachine,
        alert_callbacks: list[Callable[[ObserverAlert], None]] | None = None,
    ) -> None:
        self.governance_fsm = governance_fsm
        self._alert_callbacks = alert_callbacks or []
        self._agent_phases: dict[str, Phase] = {}
        self._eval_history: list[dict[str, Any]] = []

    # --- Event Handlers ---

    def on_fast_screen_complete(self, report: EvaluationReport) -> ObserverAlert | None:
        """
        Handle Fast-Screen completion.

        FAIL → triggers Gray Code transition: DECIDE → QUARANTINE (HALT)
        """
        self._record_eval(report)

        if report.overall_status == EvalStatus.FAIL:
            # Transition to HALT (quarantine)
            reason = f"Fast-Screen FAIL for {report.agent_id}: auto-quarantine"
            if self.governance_fsm.current_state == GovernanceState.DECIDE:
                self.governance_fsm.transition(GovernanceState.HALT, reason)
            else:
                self.governance_fsm.force_halt(reason)

            alert = ObserverAlert(
                alert_id=f"fs-fail-{report.agent_id}-{int(time.time())}",
                agent_id=report.agent_id,
                alert_type="FAST_SCREEN_QUARANTINE",
                message=f"Agent {report.agent_id} failed Fast-Screen. Quarantined.",
                severity="critical",
                metadata={"report_id": report.report_id, "score": report.overall_score},
            )
            self._notify_alert(alert)
            return alert

        # PASS — from INIT, transition to OBSERVE to start lifecycle
        if self.governance_fsm.current_state == GovernanceState.INIT:
            self.governance_fsm.transition(
                GovernanceState.OBSERVE,
                f"Fast-Screen PASS for {report.agent_id}",
            )

        alert = ObserverAlert(
            alert_id=f"fs-pass-{report.agent_id}-{int(time.time())}",
            agent_id=report.agent_id,
            alert_type="FAST_SCREEN_PASS",
            message=f"Agent {report.agent_id} passed Fast-Screen.",
            severity="info",
            metadata={"report_id": report.report_id, "score": report.overall_score},
        )
        self._notify_alert(alert)
        return alert

    def on_full_run_complete(self, report: EvaluationReport) -> ObserverAlert | None:
        """
        Handle Full-Run completion.

        Layer 5 MAS Dimension score → affects 4-phase autonomy permissions.
        """
        self._record_eval(report)

        mas_score = report.mas_dimension_score
        phase = self._map_score_to_phase(mas_score)
        self._agent_phases[report.agent_id] = phase

        # Determine governance action
        if mas_score >= 80 and report.critical_count == 0:
            # Max permissions — transition toward ACT if safe
            if self.governance_fsm.can_transition(GovernanceState.ACT):
                self.governance_fsm.transition(
                    GovernanceState.ACT,
                    f"Full-Run MAS score {mas_score:.0f} → {phase.value}",
                )
            alert = ObserverAlert(
                alert_id=f"fr-approve-{report.agent_id}-{int(time.time())}",
                agent_id=report.agent_id,
                alert_type="FULL_RUN_APPROVED",
                message=f"Agent {report.agent_id} approved with {phase.value} permissions (score={mas_score:.0f}).",
                severity="info",
                metadata={"phase": phase.value, "score": mas_score},
            )
        elif mas_score >= 50:
            # Partial permissions — transition toward VERIFY
            if self.governance_fsm.can_transition(GovernanceState.VERIFY):
                self.governance_fsm.transition(
                    GovernanceState.VERIFY,
                    f"Full-Run MAS score {mas_score:.0f} → {phase.value}",
                )
            alert = ObserverAlert(
                alert_id=f"fr-conditional-{report.agent_id}-{int(time.time())}",
                agent_id=report.agent_id,
                alert_type="FULL_RUN_CONDITIONAL",
                message=f"Agent {report.agent_id} conditional approval with {phase.value} permissions (score={mas_score:.0f}).",
                severity="warning",
                metadata={"phase": phase.value, "score": mas_score},
            )
        else:
            # Minimum permissions — force toward HALT
            self.governance_fsm.force_halt(
                f"Full-Run MAS score {mas_score:.0f} → {phase.value} (insufficient)"
            )
            alert = ObserverAlert(
                alert_id=f"fr-reject-{report.agent_id}-{int(time.time())}",
                agent_id=report.agent_id,
                alert_type="FULL_RUN_REJECTED",
                message=f"Agent {report.agent_id} rejected: {phase.value} permissions (score={mas_score:.0f}).",
                severity="critical",
                metadata={"phase": phase.value, "score": mas_score},
            )

        self._notify_alert(alert)
        return alert

    # --- Query ---

    def get_agent_phase(self, agent_id: str) -> Phase | None:
        """Get the current governance phase for an agent."""
        return self._agent_phases.get(agent_id)

    def get_eval_history(self, agent_id: str | None = None) -> list[dict[str, Any]]:
        """Get evaluation history, optionally filtered by agent."""
        if agent_id is None:
            return list(self._eval_history)
        return [e for e in self._eval_history if e.get("agent_id") == agent_id]

    # --- Internal ---

    def _record_eval(self, report: EvaluationReport) -> None:
        self._eval_history.append({
            "agent_id": report.agent_id,
            "report_id": report.report_id,
            "mode": report.test_mode.value,
            "status": report.overall_status.value,
            "score": report.overall_score,
            "mas_score": report.mas_dimension_score,
            "timestamp": time.time(),
        })

    def _map_score_to_phase(self, score: float) -> Phase:
        if score >= 80:
            return Phase.OLD_YANG
        elif score >= 50:
            return Phase.LESSER_YANG
        elif score >= 30:
            return Phase.LESSER_YIN
        else:
            return Phase.OLD_YIN

    def _notify_alert(self, alert: ObserverAlert) -> None:
        for cb in self._alert_callbacks:
            try:
                cb(alert)
            except Exception:
                pass

    def add_alert_callback(self, callback: Callable[[ObserverAlert], None]) -> None:
        self._alert_callbacks.append(callback)

    def remove_alert_callback(self, callback: Callable[[ObserverAlert], None]) -> None:
        if callback in self._alert_callbacks:
            self._alert_callbacks.remove(callback)


__all__ = [
    "Phase",
    "ObserverAlert",
    "MASEvalObserver",
]

#!/usr/bin/env python3
"""
策略规则进化提案器

综合多源燃料 (rule_effectiveness + agent_health + redline_candidates + vaccine_pipeline)
生成 PR 级策略变更提案

提案类型:
- threshold_adjustment: 探针/规则阈值调整
- new_rule: 新增治理规则
- redline_candidate: 红线模式入库
- rule_deprecation: 废弃失效规则
- rule_replacement: 规则替换重写

输出: evolution_fuel 中 policy_proposal 类型燃料，可直接转为 GitHub PR
"""

import argparse
import json
import os
import sys
from collections import defaultdict
from datetime import datetime, timezone, timedelta
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

try:
    import duckdb
    DUCKDB_AVAILABLE = True
except ImportError:
    DUCKDB_AVAILABLE = False

from maref_config import config_path

LAKE_ROOT = Path(os.environ.get("MAREF_GOVERNANCE_LAKE", "/Volumes/1TB-M2/maref-governance-lake"))


def _load_fuel(fuel_type: str, days: int = 30) -> list[dict]:
    """加载 evolution_fuel"""
    if not DUCKDB_AVAILABLE:
        return []

    try:
        conn = duckdb.connect()
        date_cutoff = (datetime.now(timezone.utc) - timedelta(days=days)).strftime("%Y%m%d")
        df = conn.execute(f"""
            SELECT * FROM read_parquet('{LAKE_ROOT}/analytics/evolution_fuel/**/*.parquet')
            WHERE date >= '{date_cutoff}' AND fuel_type = '{fuel_type}'
        """).fetchdf()
        result = []
        for _, row in df.iterrows():
            result.append(row.to_dict())
        conn.close()
        return result
    except Exception:
        return []


